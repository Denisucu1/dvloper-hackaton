def words_of_length(length: int) -> list[str]:
    """Return lowercase alphabetic words of exact length `length`, preserving priority order."""
    raw = {4: WORDS_4, 5: WORDS_5, 6: WORDS_6}.get(length, ())
    seen: set[str] = set()
    out: list[str] = []
    for w in raw:
        w_clean = "".join(ch for ch in w.lower() if "a" <= ch <= "z")
        if len(w_clean) == length and w_clean not in seen:
            seen.add(w_clean)
            out.append(w_clean)
    return out
